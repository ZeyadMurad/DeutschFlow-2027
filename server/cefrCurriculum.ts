export function evaluatePlacementLevel(
  answers: Array<{ questionId: string; selectedIndex: number }>
): { level: CEFRLevel; scorePct: number; breakdown: Record<string, { correct: number; total: number }> } {
  const byId = new Map(PLACEMENT_QUESTIONS.map((q) => [q.id, q]));
  const breakdown: Record<string, { correct: number; total: number }> = {
    A1: { correct: 0, total: 0 },
    A2: { correct: 0, total: 0 },
    B1: { correct: 0, total: 0 },
    B2: { correct: 0, total: 0 },
  };
  let totalCorrect = 0;

  for (const ans of answers) {
    const q = byId.get(ans.questionId);
    if (!q) continue;
    breakdown[q.cefrLevel].total += 1;
    if (q.correctIndex === ans.selectedIndex) {
      breakdown[q.cefrLevel].correct += 1;
      totalCorrect += 1;
    }
  }

  const totalQs = Math.max(1, PLACEMENT_QUESTIONS.length);
  const scorePct = Math.round((totalCorrect / totalQs) * 100);

  let level: CEFRLevel = 'A1';
  if (breakdown.A1.correct >= 1 && breakdown.A2.correct >= 1) level = 'A2';
  if (level === 'A2' && breakdown.B1.correct >= 2) level = 'B1';
  else if (level === 'A2' && breakdown.B1.correct >= 1 && scorePct >= 62) level = 'B1';
  if (level === 'B1' && breakdown.B2.correct >= 2 && scorePct >= 75) level = 'B2';

  return { level, scorePct, breakdown };
}
